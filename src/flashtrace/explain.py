"""Optional LLM layer: plain-language explanations of EXISTING findings.

CLAUDE.md rule 3: detection is deterministic; this layer only explains findings that
the rules already produced. It never adds, removes or edits a finding: the model's
answer is validated against the report's finding IDs and anything else is dropped.

Privacy: only the report's findings (rule, severity, title, already-redacted detail)
and evidence coordinates are sent; dump bytes and previews are not. A report produced
with ``--reveal-secrets`` is refused unless ``allow_revealed=True``.

API usage confirmed against anthropic-sdk-python v2.2.0 source:
``client.beta.messages.create(model=, max_tokens=, system=, messages=, betas=,
fallbacks="default", output_config={"format": {"type": "json_schema", ...}})``;
errors derive from ``anthropic.APIStatusError`` / ``anthropic.APIConnectionError``.
"""

from __future__ import annotations

import importlib
import json
from dataclasses import dataclass, field
from typing import Any

DEFAULT_MODEL = "claude-opus-5-5"
FALLBACK_BETA = "server-side-fallback-2026-07-01"
MAX_FINDINGS = 200  # keep requests bounded; the rest are listed as not explained

SYSTEM_PROMPT = (
    "You explain findings from FlashTrace, a deterministic forensic triage tool for "
    "ESP32 SPI flash dumps, to an incident responder. Each finding was produced by a "
    "rule and is backed by byte-level evidence. Explain what each finding means for "
    "this device, why it matters, and what to check or do next. Do not invent new "
    "findings, do not dispute the evidence, and do not guess secret values: masked "
    "values stay masked. Refer to findings only by the finding_id you were given. "
    "Write plainly and concretely."
)

SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "summary": {"type": "string"},
        "explanations": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "finding_id": {"type": "string"},
                    "explanation": {"type": "string"},
                    "next_steps": {"type": "array", "items": {"type": "string"}},
                },
                "required": ["finding_id", "explanation", "next_steps"],
                "additionalProperties": False,
            },
        },
    },
    "required": ["summary", "explanations"],
    "additionalProperties": False,
}


class ExplainError(RuntimeError):
    pass


@dataclass
class Explanation:
    model: str
    summary: str
    by_finding: dict[str, dict[str, Any]] = field(default_factory=dict)
    unexplained: list[str] = field(default_factory=list)  # finding ids with no explanation
    dropped: int = 0  # model items that referenced unknown finding ids

    def as_dict(self) -> dict[str, Any]:
        return {
            "kind": "explanation",
            "model": self.model,
            "note": "Generated by an LLM from existing findings; not evidence. "
            "Findings and evidence are unchanged.",
            "summary": self.summary,
            "explanations": self.by_finding,
            "unexplained_finding_ids": self.unexplained,
            "dropped_items": self.dropped,
        }


def build_payload(report: dict[str, Any], *, allow_revealed: bool = False) -> dict[str, Any]:
    if report.get("kind") not in ("analysis", "diff"):
        raise ExplainError("input is not a FlashTrace JSON report")
    if report.get("dump", {}).get("secrets_revealed") and not allow_revealed:
        raise ExplainError(
            "report was produced with --reveal-secrets; refusing to send unredacted values"
            " (re-run analyze without it, or pass --allow-revealed)"
        )
    findings = [
        {
            "finding_id": f["id"],
            "rule_id": f["rule_id"],
            "severity": f["severity"],
            "title": f["title"],
            "detail": f.get("detail", {}),
            "attck": f.get("attck", []),
            "evidence": [
                {k: e.get(k) for k in ("partition", "offset_hex", "length", "sha256")}
                for e in f.get("evidence", [])
            ],
        }
        for f in report.get("findings", [])[:MAX_FINDINGS]
    ]
    context = {
        "kind": report.get("kind"),
        "chip": report.get("dump", {}).get("chip"),
        "encryption": report.get("encryption"),
        "summary": report.get("summary"),
    }
    return {"context": context, "findings": findings}


def explain_report(
    report: dict[str, Any],
    *,
    client: Any | None = None,
    model: str = DEFAULT_MODEL,
    allow_revealed: bool = False,
) -> Explanation:
    payload = build_payload(report, allow_revealed=allow_revealed)
    known = [f["finding_id"] for f in payload["findings"]]
    if not known:
        return Explanation(model=model, summary="The report contains no findings.")
    if client is None:
        sdk = _sdk()
        if sdk is None:
            raise ExplainError(
                "the explain command needs the Anthropic SDK: pip install 'flashtrace[explain]'"
            )
        client = sdk.Anthropic()
    response = _call(client, model, payload)
    if response.stop_reason == "refusal":
        raise ExplainError("the model declined to explain this report (refusal)")
    if response.stop_reason == "max_tokens":
        raise ExplainError("the explanation was cut off (max_tokens); try fewer findings")
    text = next((b.text for b in response.content if getattr(b, "type", "") == "text"), "")
    try:
        data = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ExplainError(f"model returned invalid JSON: {exc}") from exc
    by_id: dict[str, dict[str, Any]] = {}
    dropped = 0
    known_set = set(known)
    for item in data.get("explanations", []):
        fid = item.get("finding_id")
        if fid in known_set and fid not in by_id:
            by_id[fid] = {
                "explanation": str(item.get("explanation", "")),
                "next_steps": [str(s) for s in item.get("next_steps", [])],
            }
        else:
            dropped += 1
    return Explanation(
        model=str(getattr(response, "model", model)),
        summary=str(data.get("summary", "")),
        by_finding=by_id,
        unexplained=[fid for fid in known if fid not in by_id],
        dropped=dropped,
    )


def _sdk() -> Any | None:
    """The anthropic module when installed (for typed errors), else None."""
    try:
        return importlib.import_module("anthropic")
    except ImportError:
        return None


def _call(client: Any, model: str, payload: dict[str, Any]) -> Any:
    kwargs: dict[str, Any] = {
        "model": model,
        "max_tokens": 16000,
        "system": SYSTEM_PROMPT,
        "messages": [
            {
                "role": "user",
                "content": "Explain these FlashTrace findings. Report JSON:\n"
                + json.dumps(payload, indent=1, sort_keys=True, default=str),
            }
        ],
        "output_config": {"format": {"type": "json_schema", "schema": SCHEMA}},
        "betas": [FALLBACK_BETA],
        "fallbacks": "default",
    }
    sdk = _sdk()
    if sdk is None:  # injected client, SDK not installed
        return client.beta.messages.create(**kwargs)
    try:
        return client.beta.messages.create(**kwargs)
    except sdk.AuthenticationError as exc:
        raise ExplainError("Anthropic authentication failed: set ANTHROPIC_API_KEY") from exc
    except sdk.RateLimitError as exc:
        raise ExplainError("Anthropic rate limit reached; retry later") from exc
    except sdk.BadRequestError as exc:
        raise ExplainError(f"request rejected by the API: {exc.message}") from exc
    except sdk.APIStatusError as exc:
        raise ExplainError(f"Anthropic API error {exc.status_code}: {exc.message}") from exc
    except sdk.APIConnectionError as exc:
        raise ExplainError("could not reach the Anthropic API") from exc


def render_markdown(exp: Explanation, report: dict[str, Any]) -> str:
    titles = {
        f["id"]: (f["severity"], f["rule_id"], f["title"]) for f in report.get("findings", [])
    }
    lines = [
        "# FlashTrace explanation",
        "",
        f"> Generated by `{exp.model}` from the existing findings. It is not evidence;"
        " the findings and their evidence in the report are unchanged.",
        "",
        "## Summary",
        "",
        exp.summary or "_No summary returned._",
        "",
        "## Findings",
    ]
    for fid, item in exp.by_finding.items():
        sev, rule, title = titles.get(fid, ("?", "?", fid))
        lines += ["", f"### {sev} · `{rule}` · {title}", "", item["explanation"]]
        if item["next_steps"]:
            lines += ["", "Next steps:", *[f"- {s}" for s in item["next_steps"]]]
    if exp.unexplained:
        lines += ["", "## Not explained", "", *[f"- `{fid}`" for fid in exp.unexplained]]
    return "\n".join(lines) + "\n"
