"""Generate docs/rules.md from the rule registry + ATT&CK map, and the README benchmark table.

Usage: python -m tools.gen_docs   (rewrites docs/rules.md and the README table in place)
Tests call :func:`rules_markdown` / :func:`readme_with_bench` to ensure both are current.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from flashtrace.attck import load_map
from flashtrace.bench import markdown_table
from flashtrace.diff import DIFF_RULES
from flashtrace.rules import load_rules

ROOT = Path(__file__).resolve().parents[1]
RULES_MD = ROOT / "docs" / "rules.md"
README = ROOT / "README.md"
BENCH_JSON = ROOT / "examples" / "bench_results.json"
BEGIN, END = "<!-- BENCH:BEGIN -->", "<!-- BENCH:END -->"


def _attck(rule_id: str) -> str:
    m = load_map().get(rule_id)
    if m is None:
        return "unmapped"
    if m.technique and not m.review:
        return f"{m.technique} (confirmed)"
    if m.technique:
        return f"{m.technique} proposed — needs review"
    return "none — needs review"


def rules_markdown() -> str:
    out = [
        "# FlashTrace rules",
        "",
        "Generated by `python -m tools.gen_docs` from the rule registry and",
        "`src/flashtrace/data/attck_ics_map.yaml`. Do not edit by hand.",
        "",
        "Every finding cites evidence (absolute offset, length, partition, SHA-256 of the",
        "exact bytes). Secret values are redacted unless `--reveal-secrets` is given; the",
        "SHA-256 of the unredacted value is always stored.",
        "",
        "## Summary",
        "",
        "| Rule | Severity | ATT&CK for ICS |",
        "|---|---|---|",
    ]
    rules = load_rules()
    for rid, r in rules.items():
        out.append(f"| [`{rid}`](#{rid.lower().replace('.', '')}) | {r.severity} | {_attck(rid)} |")
    for rid, (sev, _title) in sorted(DIFF_RULES.items()):
        out.append(f"| `{rid}` (diff only) | {sev} | {_attck(rid)} |")
    for rid, r in rules.items():
        note = load_map().get(rid)
        out += [
            "",
            f"## {rid}",
            "",
            f"**Severity:** {r.severity} · **ATT&CK for ICS:** {_attck(rid)}",
            "",
            f"**{r.title}.** {r.description}",
            "",
            f"**False positives:** {r.false_positives or 'none known.'}",
        ]
        if note and note.note:
            out += ["", f"**Mapping note:** {note.note}"]
    out += [
        "",
        "## DIFF.* (flashtrace diff)",
        "",
        "Emitted only by `flashtrace diff dumpA dumpB`. Evidence points into the dump the",
        "bytes come from (`detail.evidence_dumps`).",
        "",
        "| Rule | Severity | Meaning |",
        "|---|---|---|",
        *(f"| `{rid}` | {sev} | {title} |" for rid, (sev, title) in sorted(DIFF_RULES.items())),
    ]
    return "\n".join(out) + "\n"


def readme_with_bench(readme: str, bench: dict[str, object]) -> str:
    table = markdown_table(bench)  # type: ignore[arg-type]
    block = f"{BEGIN}\n{table}{END}"
    return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _m: block, readme, flags=re.S)


def main() -> int:
    RULES_MD.parent.mkdir(exist_ok=True)
    RULES_MD.write_text(rules_markdown(), encoding="utf-8")
    bench = json.loads(BENCH_JSON.read_text())
    README.write_text(readme_with_bench(README.read_text(), bench), encoding="utf-8")
    print(f"wrote {RULES_MD} and README benchmark table")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
